export function getTopicalArticle(slug) {
  return BED_TOPICAL_ARTICLES.find((article) => article.slug === slug) || null;
}

export function mergeJournalPosts(dynamicPosts = []) {
  const bySlug = new Map(BED_TOPICAL_ARTICLES.map((post) => [post.slug, post]));
  for (const post of dynamicPosts || []) if (post?.slug) bySlug.set(post.slug, { ...bySlug.get(post.slug), ...post });
  return [...bySlug.values()].filter((post) => post.published !== false).sort((a, b) => new Date(b.publishedAt || 0) - new Date(a.publishedAt || 0));
}
