export function getBedSemanticLanding(slug = '') {
  return BED_SEMANTIC_LANDINGS[String(slug || '').toLowerCase()] || null;
}

function normalizeSize(value = '') {
  const m = String(value).toLowerCase().replace(/см/g, '').replace(/[xх×]/g, '×').replace(/\s+/g, '').match(/(\d{2,3})×(\d{2,3})/);
  return m ? `${m[1]}×${m[2]}` : '';
}

function productText(p) {
  return `${p?.name || ''} ${p?.shortDescription || ''} ${p?.fullDescription || ''} ${p?.material || ''} ${(p?.fabrics || []).join(' ')} ${(p?.colors || []).join(' ')}`.toLowerCase();
}

export function filterProductsForBedLanding(products = [], landing = null) {
  if (!landing?.match || landing.match.all) return products;
  const rule = landing.match;
  return products.filter((p) => {
    if (rule.maxPrice != null && Number(p.price || 0) > rule.maxPrice) return false;
    const sizes = (p.sizes || []).map(normalizeSize).filter(Boolean);
    if (rule.sizes?.length && !rule.sizes.some((s) => sizes.includes(normalizeSize(s)))) return false;
    if (rule.minWidth != null && !sizes.some((s) => Number(s.split('×')[0]) >= rule.minWidth)) return false;
    if (rule.textAny?.length) {
      const text = productText(p);
      if (!rule.textAny.some((needle) => text.includes(String(needle).toLowerCase()))) return false;
    }
    return true;
  });
}

export function semanticCoreSummary() {
  const landings = Object.entries(BED_SEMANTIC_LANDINGS).map(([slug, item]) => ({
    slug,
    priority: item.priority,
    intent: item.intent,
    h1: item.h1,
    keywordCount: item.keywords.length,
    primaryKeyword: item.keywords[0],
  }));
  return {
    landingCount: landings.length,
    mappedKeywordCount: landings.reduce((sum, x) => sum + x.keywordCount, 0),
    supportingKeywordCount: BED_SUPPORTING_KEYWORDS.length,
    landings,
  };
}
